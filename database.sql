CREATE TABLE users(
 id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(140) NOT NULL,username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,role ENUM('admin','guru','pengawas','siswa') NOT NULL,
 nisn VARCHAR(40) NULL,class_name VARCHAR(80) NULL,active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE subjects(id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(140) NOT NULL,teacher_id INT NULL,
 FOREIGN KEY(teacher_id) REFERENCES users(id) ON DELETE SET NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE exams(id INT AUTO_INCREMENT PRIMARY KEY,title VARCHAR(180) NOT NULL,subject_id INT NULL,class_name VARCHAR(80) NOT NULL,
 start_at DATETIME NOT NULL,duration_minutes INT NOT NULL DEFAULT 60,token VARCHAR(30) NOT NULL,
 status ENUM('draft','published','closed') NOT NULL DEFAULT 'draft',shuffle_questions TINYINT(1) NOT NULL DEFAULT 1,
 shuffle_options TINYINT(1) NOT NULL DEFAULT 1,created_by INT NULL,
 FOREIGN KEY(subject_id) REFERENCES subjects(id) ON DELETE SET NULL,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE questions(id INT AUTO_INCREMENT PRIMARY KEY,exam_id INT NOT NULL,question_text TEXT NOT NULL,
 options_json JSON NULL,correct_answer VARCHAR(5) NULL,points DECIMAL(7,2) NOT NULL DEFAULT 1,
 question_type ENUM('mcq','essay') NOT NULL DEFAULT 'mcq',
 FOREIGN KEY(exam_id) REFERENCES exams(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE attempts(id INT AUTO_INCREMENT PRIMARY KEY,exam_id INT NOT NULL,student_id INT NOT NULL,
 started_at DATETIME NOT NULL,ends_at DATETIME NOT NULL,submitted_at DATETIME NULL,
 status ENUM('in_progress','submitted','interrupted') NOT NULL DEFAULT 'in_progress',score DECIMAL(8,2) NULL,
 UNIQUE KEY uniq_attempt(exam_id,student_id),FOREIGN KEY(exam_id) REFERENCES exams(id) ON DELETE CASCADE,
 FOREIGN KEY(student_id) REFERENCES users(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE attempt_questions(id INT AUTO_INCREMENT PRIMARY KEY,attempt_id INT NOT NULL,question_id INT NOT NULL,sort_order INT NOT NULL,
 UNIQUE KEY uq_attempt_question(attempt_id,question_id),FOREIGN KEY(attempt_id) REFERENCES attempts(id) ON DELETE CASCADE,
 FOREIGN KEY(question_id) REFERENCES questions(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE answers(id INT AUTO_INCREMENT PRIMARY KEY,attempt_id INT NOT NULL,question_id INT NOT NULL,answer_text TEXT NULL,
 is_correct TINYINT(1) NULL,points_awarded DECIMAL(7,2) NULL,updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_answer(attempt_id,question_id),FOREIGN KEY(attempt_id) REFERENCES attempts(id) ON DELETE CASCADE,
 FOREIGN KEY(question_id) REFERENCES questions(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE activity_logs(id INT AUTO_INCREMENT PRIMARY KEY,attempt_id INT NOT NULL,event_type VARCHAR(60) NOT NULL,
 detail VARCHAR(255) NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(attempt_id) REFERENCES attempts(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
